from typing import Optional
from sqlalchemy import Boolean, Float, ForeignKey, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.models.base import Base, TimestampMixin, UUIDMixin


class OptimizationRecommendation(Base, UUIDMixin, TimestampMixin):
    """
    Optimization Recommendation Entity
    Stores predictions generated by the Machine Learning model,
    including the extracted feature vector snapshot and explainability justification.
    """
    __tablename__ = "optimization_recommendations"

    source_file_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("source_files.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    recommended_level: Mapped[str] = mapped_column(String(4), nullable=False)
    confidence_score: Mapped[float] = mapped_column(Float, nullable=False)
    objective: Mapped[str] = mapped_column(String(20), nullable=False, default="SPEED")
    features_extracted: Mapped[dict] = mapped_column(JSON, nullable=False)
    explanation: Mapped[str] = mapped_column(Text, nullable=False)
    actual_best_level: Mapped[Optional[str]] = mapped_column(String(4), nullable=True)
    prediction_verified: Mapped[Optional[bool]] = mapped_column(Boolean, nullable=True)

    # Relationships
    source_file = relationship("SourceFile", backref="recommendations")

    def __repr__(self) -> str:
        return (
            f"<OptimizationRecommendation(id='{self.id}', rec='{self.recommended_level}', "
            f"confidence={self.confidence_score:.2f})>"
        )
